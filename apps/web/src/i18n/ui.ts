const messages: Record<Locale, Record<UiKey, string>> = {
	en,
	"zh-Hans": zhHans,
};

export function t(
	locale: Locale,
	key: UiKey,
	vars?: Record<string, string | number>,
): string {
	const resolved = parseLocale(locale) ?? DEFAULT_LOCALE;
	let text = messages[resolved][key] ?? en[key];
	if (!vars) return text;
	for (const [name, value] of Object.entries(vars)) {
		text = text.replaceAll(`{${name}}`, String(value));
	}
	return text;
}

const categoryKeys: Record<string, UiKey> = {
	Method: "categoryMethod",
	Discovery: "categoryDiscovery",
	Inspection: "categoryInspection",
	Validation: "categoryValidation",
	Structure: "categoryStructure",
	"Research output": "categoryResearchOutput",
};

export function categoryLabel(locale: Locale, category: string): string {
	const key = categoryKeys[category];
	return key ? t(locale, key) : category;
}
